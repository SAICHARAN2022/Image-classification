import os

dataset_path = "/home/houzeo/Documents/Saicharan/Intel Image Dataset/Intel Image Dataset/Intel Image Dataset/"


test = "/home/houzeo/Documents/Saicharan/test/test"

print(os.listdir(dataset_path))

import tensorflow as tf
from tensorflow import keras
from tensorflow.keras import Sequential
from tensorflow.keras.layers import Conv2D, MaxPooling2D, Flatten, Dense, Dropout

#generators
train_ds = tf.keras.utils.image_dataset_from_directory(
    dataset_path,
    image_size=(150, 150),
    batch_size=32,
    shuffle=True
)


#generators
test_ds = tf.keras.utils.image_dataset_from_directory(
    test,
    image_size=(150, 150),
    batch_size=32,
    shuffle=True
)


test_ds

def process(image,label):
  image = tf.cast(image/255. , tf.float32)
  return image, label
train_ds = train_ds.map(process)
class_names = test_ds.class_names
test_ds = test_ds.map(process)




# create CNN model
model = Sequential()
model.add(Conv2D(32,kernel_size=(3,3),padding='valid',activation='relu',input_shape=(150,150,3)))
model.add(MaxPooling2D(pool_size=(2,2),strides=2,padding='valid'))



model.add(Conv2D(64,kernel_size=(3,3),padding='valid',activation='relu',input_shape=(150,150,3)))
model.add(MaxPooling2D(pool_size=(2,2),strides=2,padding='valid'))



model.add(Conv2D(128,kernel_size=(3,3),padding='valid',activation='relu',input_shape=(150,150,3)))
model.add(MaxPooling2D(pool_size=(2,2),strides=2,padding='valid'))

model.add(Flatten())


model.add(Dense(128,activation='relu'))
model.add(Dropout(0.5))
model.add(Dense(6, activation='softmax'))

model.summary()

model.compile(
    optimizer='adam',
    loss='sparse_categorical_crossentropy',
    metrics=['accuracy']
)

early_stop = tf.keras.callbacks.EarlyStopping(
    monitor='val_loss', patience=3, restore_best_weights=True
)
model.fit(train_ds,epochs=20,validation_data=test_ds,callbacks=[early_stop])

model.save("intel_cnn.keras")

import numpy as np
